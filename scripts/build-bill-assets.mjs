// Packs assets/bills/* into src/lib/bill-format-assets.ts as base64 strings,
// so the bill PDFs can use them on the server without reading files at run time.
import { readFileSync, writeFileSync } from "fs";
import { join } from "path";

const dir = join(process.cwd(), "assets", "bills");
const files = {
  caLogo: "ca-logo.png",
  advocateLogo: "advocate-logo.png",
  bedgeLogo: "bedge-logo.png",
  qrGst: "qr-gst.png",
  qrNonGst: "qr-non-gst.png",
  qrNonGstHv: "qr-non-gst-hv.png",
  qrNonGstVla: "qr-non-gst-vla.png",
  qrBedge: "qr-bedge.png",
  fontBold: "BillSans-Bold.ttf",
  fontRegular: "BillSans-Regular.ttf",
};

const lines = [
  "// Generated by scripts/build-bill-assets.mjs from assets/bills; do not edit.",
  "",
  ...Object.entries(files).map(([key, file]) => `export const ${key} = "${readFileSync(join(dir, file)).toString("base64")}";`),
  "",
];
writeFileSync(join(process.cwd(), "src", "lib", "bill-format-assets.ts"), lines.join("\n"));
console.log("Wrote src/lib/bill-format-assets.ts");
